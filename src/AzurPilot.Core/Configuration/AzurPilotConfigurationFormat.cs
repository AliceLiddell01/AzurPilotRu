namespace AzurPilot.Core.Configuration;

/// <summary>Формат файла, из которого прочитана пользовательская конфигурация.</summary>
/// <remarks>
/// Формат — не деталь реализации: он отличает канонический YAML-документ схемы v3 от legacy JSON,
/// который допускается только как вход и нормализуется в памяти. Потребитель диагностики видит
/// формат источника, не разбирая путь файла.
/// </remarks>
public enum AzurPilotConfigurationFormat
{
    /// <summary>Файла нет: конфигурация собрана из встроенных значений по умолчанию.</summary>
    None,

    /// <summary>Legacy-документ JSON схемы v1 или v2, нормализованный к схеме v3 в памяти.</summary>
    Json,

    /// <summary>Канонический YAML-документ эффективной схемы v3.</summary>
    Yaml,
}
