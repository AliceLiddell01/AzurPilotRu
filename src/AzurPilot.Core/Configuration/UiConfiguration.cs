using System.Text.Json.Serialization;

namespace AzurPilot.Core.Configuration;

/// <summary>Секция настроек операторского интерфейса схемы v3.</summary>
/// <remarks>
/// <para>
/// Секция появилась вместе с реальным пользовательским решением — выбором режима операторского
/// интерфейса. Настройки presentation-слоя, не влияющие на доступные действия (цвета, рамки, размеры
/// панелей), сюда не добавляются: настройка появляется вместе с реализованной capability, которая её
/// действительно читает.
/// </para>
/// <para>
/// Экземпляр неизменяем и является частью snapshot: он создаётся при загрузке конфигурации и не
/// обновляется при изменении файла на диске.
/// </para>
/// </remarks>
public sealed record UiConfiguration
{
    /// <summary>Режим запуска операторского интерфейса.</summary>
    /// <value>
    /// Обязательный ключ <c>ui.mode</c>. Принимаются ровно три строки в нижнем регистре: <c>normal</c>,
    /// <c>manual</c> и <c>diagnostic</c>. Другой регистр, числовая форма и любое иное значение
    /// отвергаются загрузкой как несоответствие схеме v3.
    /// </value>
    [JsonPropertyName("mode")]
    public required OperatorUiMode Mode { get; init; }
}
