namespace AzurPilot.Core.Configuration;

/// <summary>
/// Режим запуска операторского интерфейса: объём доступных пользователю действий.
/// </summary>
/// <remarks>
/// <para>
/// Режим — это настоящее presentation-правило, а не косметическая настройка: он определяет, какие
/// действия видимы в палитре и какие разрешены к исполнению при прямом вводе команды. Значения
/// упорядочены по возрастанию объёма: <see cref="Normal"/> содержит только пользовательские операции,
/// <see cref="Manual"/> добавляет ручное управление отдельными операциями, <see cref="Diagnostic"/>
/// добавляет полный технический инструментарий.
/// </para>
/// <para>
/// Режим принадлежит пользовательской конфигурации (<c>ui.mode</c>) и может быть переопределён явным
/// аргументом запуска <c>--mode</c>; приоритет аргумента принадлежит точке входа приложения.
/// </para>
/// </remarks>
public enum OperatorUiMode
{
    /// <summary>Основной пользовательский режим: только необходимые для работы действия.</summary>
    Normal = 0,

    /// <summary>Ручное управление отдельными поддерживаемыми операциями.</summary>
    Manual = 1,

    /// <summary>Полный технический инструментарий, включая ручные возможности.</summary>
    Diagnostic = 2,
}
