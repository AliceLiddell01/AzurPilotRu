namespace AzurPilot.Core.Android;

/// <summary>
/// Наблюдённое присутствие пакета на точном endpoint-е.
/// </summary>
/// <remarks>
/// <para>
/// Различаются три случая, и «не удалось спросить» не выдаётся за «пакета нет»:
/// <see cref="Installed"/> — устройство подтвердило установку, <see cref="Absent"/> — устройство
/// ответило, что пакета нет, <see cref="QueryFailed"/> — запрос не дал распознанного ответа, поэтому
/// присутствие не доказано ни в одну сторону.
/// </para>
/// <para>
/// Значение относится к запрошенному endpoint-у и запрошенному пакету: ответ про другой endpoint или
/// другой пакет наблюдением не является.
/// </para>
/// </remarks>
public enum AndroidPackagePresence
{
    /// <summary>Пакет установлен: устройство подтвердило его присутствие.</summary>
    Installed = 0,

    /// <summary>Пакет отсутствует: устройство ответило, что пакета нет.</summary>
    Absent = 1,

    /// <summary>Присутствие не доказано: запрос к устройству не дал распознанного ответа.</summary>
    QueryFailed = 2,
}
