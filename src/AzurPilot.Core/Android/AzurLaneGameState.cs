namespace AzurPilot.Core.Android;

/// <summary>
/// Состояние игры Azur Lane, выведенное из независимых наблюдённых фактов.
/// </summary>
/// <remarks>
/// <para>
/// Состояние не выдумывается: <see cref="Unknown"/> означает, что наблюдение не доказало ни одного
/// состояния, и это честный исход, а не «вероятно, остановлено». Отсутствие установки и отсутствие
/// процесса — разные состояния, а <see cref="Background"/> и <see cref="Foreground"/> различаются
/// наблюдением переднего плана, а не наличием процесса.
/// </para>
/// <para>
/// Переходы между состояниями подтверждаются наблюдением: ни код выхода команды ADB, ни факт запуска
/// процесса состоянием не являются.
/// </para>
/// </remarks>
public enum AzurLaneGameState
{
    /// <summary>Пакет игры не установлен.</summary>
    NotInstalled = 0,

    /// <summary>Игра установлена, но её процесс не наблюдается.</summary>
    Stopped = 1,

    /// <summary>Процесс игры наблюдается, но игра не находится на переднем плане.</summary>
    Background = 2,

    /// <summary>Игра находится на переднем плане.</summary>
    Foreground = 3,

    /// <summary>Состояние не доказано наблюдением.</summary>
    Unknown = 4,
}
