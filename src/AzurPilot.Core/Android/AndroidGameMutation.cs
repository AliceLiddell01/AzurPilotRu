namespace AzurPilot.Core.Android;

/// <summary>
/// Примитив host-side поверхности Android: однократная mutation игры на точном endpoint-е.
/// </summary>
/// <remarks>
/// <para>
/// Тип описывает ровно то, что умеет выполнить host: запуск launcher-компонента пакета и принудительную
/// остановку процессов пакета. Он используется только в <see cref="IAndroidHost"/> и не является
/// публичной операцией сервиса.
/// </para>
/// <para>
/// Перезапуск примитивом не является: orchestration доказывает его композицией mutation, поэтому
/// реализация host-а не обязана поддерживать ветку, которую production никогда не вызывает. Mutation
/// выполняется только над запрошенным пакетом: host не управляет другими пакетами и не завершает чужие
/// процессы.
/// </para>
/// </remarks>
public enum AndroidGameMutation
{
    /// <summary>Запустить игру: адресовать launcher-компонент пакета.</summary>
    Start = 0,

    /// <summary>Принудительно остановить игру: завершить процессы пакета.</summary>
    ForceStop = 1,
}
